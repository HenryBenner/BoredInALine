const dayNames = ['Sunday', 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday'] as const;

export function getCurrentCrowdedness(barName: string): number {
  const mappedName = barNameMapping[barName] || barName;
  const barData = popularTimesData[mappedName];
  
  if (!barData) {
    return -1;
  }
  
  const now = new Date();
  const estOffset = -5 * 60;
  const utcOffset = now.getTimezoneOffset();
  const estTime = new Date(now.getTime() + (utcOffset + estOffset) * 60 * 1000);
  
  const dayName = dayNames[estTime.getDay()];
  const hour = estTime.getHours().toString();
  
  const dayData = barData[dayName];
  if (!dayData) {
    return 0;
  }
  
  return dayData[hour] || 0;
}

